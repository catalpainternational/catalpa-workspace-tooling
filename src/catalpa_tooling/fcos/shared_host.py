def _q(text: str, indent: int) -> list[str]:
    pad = " " * indent
    return [pad + "inline: |"] + [(pad + "  " + line) if line else "" for line in text.rstrip("\n").split("\n")]


def _owned(name: str) -> list[str]:
    return ["      user:", f"        name: {name}", "      group:", f"        name: {name}"]


def host_bu(host: HostConfig, header: str) -> str:
    everyone = [*host.accounts, host.edge]
    out = [
        header.rstrip("\n"),
        "# Compile in this directory (or `dk host <dir> ignition`):",
        '#   podman run --rm -v "$PWD":/work:Z -w /work quay.io/coreos/butane:release \\',
        "#     --strict --files-dir . host.bu > host.ign",
        "variant: fcos",
        "version: 1.6.0",
        "",
        "passwd:",
        "  users:",
        "    # Admins: passwordless sudo (FCOS default). No app runs here.",
        "    - name: core",
        "    # One account per env (or per site and colour), each made only here, at first boot.",
    ]
    for a in everyone:
        out += [f"    - name: {a.name}", f"      uid: {a.uid}"]
    out += ["", "storage:", "  directories:", f"    - path: {host.data_mount}", "      mode: 0755"]
    for a in host.accounts:
        out += [f"    - path: {host.data_dir(a)}", "      mode: 0755"]
    for a in everyone:
        out += [
            f"    # {a.name}'s quadlets: root's, readable by {a.name} only.",
            f"    - path: {a.quadlet_dir}",
            "      mode: 0750",
            "      group:",
            f"        name: {a.name}",
        ]
        dirs = [
            (".config", "0755"), (".config/systemd", "0755"), (".config/systemd/user", "0755"),
            (".config/systemd/user/sockets.target.wants", "0755"),
            (".config/systemd/user/timers.target.wants", "0755"),
            (".config/systemd/user/default.target.wants", "0755"),
            (".config/environment.d", "0755"), (".config/containers", "0700"),
            (".local", "0755"), (".local/state", "0755"),
            (".ssh", "0700"), (".ssh/authorized_keys.d", "0700"),
        ]  # fmt: skip
        if a.name == EDGE_USER:
            dirs.append((".config/edge", "0755"))
        for d, mode in dirs:
            out += [f"    - path: {a.home}/{d}", f"      mode: {mode}", *_owned(a.name)]
    out += ["    - path: /etc/dk", "      mode: 0755"]

    out += [
        "",
        "  links:",
        "    - path: /etc/localtime",
        f"      target: ../usr/share/zoneinfo/{host.timezone}",
        "      overwrite: true",
    ]
    for a in host.accounts:
        out += [
            "    # Docker-compatible API for dk.",
            f"    - path: {a.home}/.config/systemd/user/sockets.target.wants/podman.socket",
            "      target: /usr/lib/systemd/user/podman.socket",
            *_owned(a.name),
        ]
    out += [
        f"    - path: {host.edge.home}/.config/systemd/user/sockets.target.wants/edge.socket",
        "      target: ../edge.socket",
        *_owned(EDGE_USER),
    ]

    subids = f"core:{CORE_SUBUID_START}:{SUBUID_COUNT}\n" + "".join(
        f"{a.name}:{a.subuid_start}:{SUBUID_COUNT}\n" for a in everyone
    )
    w = host.update_window
    days = ", ".join(f'"{d}"' for d in w.days)
    allow = " ".join(["core", *(a.name for a in host.accounts)])
    files: list[tuple[str, str, str, str | None, str]] = [
        # (comment, path, mode, owner, text)
        ("Pinned subordinate IDs, from each account's slot.", "/etc/subuid", "0644", None, subids),
        ("", "/etc/subgid", "0644", None, subids),
        ("", "/etc/hostname", "0644", None, f"{host.hostname}\n"),
        (
            f"OS updates and their reboot only in this window ({host.timezone}).",
            "/etc/zincati/config.d/55-updates-strategy.toml", "0644", None,
            (
                '[updates]\nstrategy = "periodic"\n\n[updates.periodic]\n'
                f'time_zone = "{host.timezone}"\n\n[[updates.periodic.window]]\n'
                f'days = [ {days} ]\nstart_time = "{w.start}"\nlength_minutes = {w.minutes}\n'
            ),
        ),
        (
            "Lets the edge's systemd open 80 and 443 (edge.socket).",
            "/etc/sysctl.d/50-unprivileged-ports.conf", "0644", None,
            "net.ipv4.ip_unprivileged_port_start = 80\n",
        ),
        (
            "Hardening: keys only, no root, few tries; only these accounts log in.",
            "/etc/ssh/sshd_config.d/10-hardening.conf", "0644", None,
            (
                "PasswordAuthentication no\nKbdInteractiveAuthentication no\nPermitRootLogin no\n"
                f"MaxAuthTries 3\nX11Forwarding no\nAllowUsers {allow}\n"
            ),
        ),
        (
            "Hardening: no LLMNR or mDNS.",
            "/etc/systemd/resolved.conf.d/10-no-llmnr.conf", "0644", None,
            "[Resolve]\nLLMNR=no\nMulticastDNS=no\n",
        ),
        (
            "admin_keys: admins, root through sudo.",
            "/var/home/core/.ssh/authorized_keys.d/dk", "0600", "core",
            "".join(f"{k}\n" for k in host.admin_keys),
        ),
        ("", "/etc/dk/loopback.nft", "0644", None, firewall_nft(host)),
    ]  # fmt: skip
    if host.insecure_registries:
        files.append(
            ("insecure_registries: plain-HTTP test registries.",
             "/etc/containers/registries.conf.d/50-dk-insecure.conf", "0644", None,
             "".join(f'[[registry]]\nlocation = "{r}"\ninsecure = true\n\n' for r in host.insecure_registries))
        )  # fmt: skip
    for a in everyone:
        files += [
            (f"{a.name}'s systemd starts at boot with nobody logged in.",
             f"/var/lib/systemd/linger/{a.name}", "0644", None, ""),
            ("", f"{a.home}/.config/environment.d/10-registry-auth.conf", "0644", a.name,
             f"REGISTRY_AUTH_FILE={a.home}/.config/containers/auth.json\n"),
        ]  # fmt: skip
    for a in host.accounts:
        files.append(
            ("ssh_authorized_keys: dk and CI, no sudo.", f"{a.home}/.ssh/authorized_keys.d/dk",
             "0600", a.name, "".join(f"{k}\n" for k in host.ssh_authorized_keys))
        )  # fmt: skip
    files += [
        ("The shared edge.", f"{host.edge.quadlet_dir}/edge.container", "0644", None, edge_container(host)),
        ("", f"{host.edge.home}/.config/systemd/user/edge.socket", "0644", EDGE_USER,
         socket_unit("the shared edge's sockets (80, 443, 443/udp)")),
    ]  # fmt: skip
    out += ["", "  files:"]
    for comment, path, mode, owner, text in files:
        if comment:
            out.append(f"    # {comment}")
        out += [f"    - path: {path}", f"      mode: {mode}"]
        if path in ("/etc/subuid", "/etc/subgid", "/etc/hostname"):
            out.append("      overwrite: true")
        if owner:
            out += _owned(owner)
        if text:
            out += ["      contents:", *_q(text, 8)]
    out += [
        f"    - path: {host.edge.home}/.config/edge/caddy.json",
        "      mode: 0644",
        *_owned(EDGE_USER),
        "      contents:",
        "        local: edge/caddy.json",
    ]

    from catalpa_tooling.fcos.butane import MASKED_UNITS

    out += [
        "",
        "systemd:",
        "  units:",
        "    # Rootless quadlets wait for network-online.target, which nothing else pulls in.",
        "    - name: multi-user.target",
        "      dropins:",
        "        - name: 10-network-online.conf",
        "          contents: |",
        "            [Unit]",
        "            Wants=network-online.target",
        "    - name: dk-loopback-firewall.service",
        "      enabled: true",
        "      contents: |",
        *("        " + line if line else "" for line in FIREWALL_UNIT.rstrip("\n").split("\n")),
        "    # Only admin_keys log in as core: afterburn would add the droplet's account keys.",
    ]
    for unit in MASKED_UNITS:
        out += [f"    - name: {unit}", "      mask: true"]
    return "\n".join(out) + "\n"


