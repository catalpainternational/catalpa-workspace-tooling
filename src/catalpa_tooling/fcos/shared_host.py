"""A server shared by several envs, possibly of several projects: ``<host dir>/host.yaml``.

.. code-block:: yaml

    hostname: shared-1
    timezone: Asia/Dili
    admin_keys: [...]            # core: admins, root through sudo
    ssh_authorized_keys: [...]   # every account: dk and CI, no sudo
    update_window: {days: [Sun], start: "02:00", minutes: 60}
    data_mount: /var/mnt/data    # each account's data in <data_mount>/<account>
    edge: {image: docker.io/library/caddy:2.11.4-alpine, tls: acme}   # or tls: internal
    retired_slots: [5]           # slots of accounts that are gone: never handed out again
    accounts:                    # all made at first boot; none is added or removed later
      - {name: deploy, slot: 1, project: nextgen, env: staging, names: [nextgen.example.org]}
      - {name: site, slot: 2, project: partisipa, env: staging, role: site,
         names: [partisipa.example.org]}
      - {name: blue, slot: 3, project: partisipa, env: staging, role: blue}
      - {name: green, slot: 4, project: partisipa, env: staging, role: green}

An env (``docker/envs/<env>/info.yaml``) names its host's folder with ``host:``, a path relative
to the project (``docker/hosts/shared-1``, or a checkout of a hosts repo several projects
share). The env's accounts are the ones with its project and env name: one account (role
``env``, the default) for a plain env, or ``site``, ``blue`` and ``green`` for a blue/green site.

A slot fixes an account's uid (1000 + slot), its subordinate IDs (65,536 from
``SUBUID_START + (slot - 1) * 65536``) and its ten loopback ports (``20000 + slot * 10`` on), so
nobody picks numbers by hand. The shared edge (account ``edge``) ends TLS for every name and
sends it to its account's first port.

``dk host <dir> render`` writes ``<dir>/generated/``: ``host.bu`` (the server, every account,
the edge and a loopback firewall) and what it embeds. Ignition runs once, at first boot, so a
new account means a new server: nothing in dk adds one to a running server.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from catalpa_tooling.fcos.caddy_json import rewrite_listeners, socket_unit
from catalpa_tooling.fcos.settings import (
    CORE_SUBUID_START,
    SUBUID_COUNT,
    SUBUID_START,
    UpdateWindow,
)

ROLES = ("env", "site", "blue", "green")
COLOURS = ("blue", "green")
#: The shared edge's account. Slots 1-30 are for envs.
EDGE_USER = "edge"
EDGE_SLOT = 31
MAX_SLOT = EDGE_SLOT - 1
PORT_BASE = 20000
PORTS_PER_SLOT = 10
DEFAULT_EDGE_IMAGE = "docker.io/library/caddy:2.11.4-alpine"
#: Containers reach other accounts' ports on the host's loopback at this address (pasta's
#: --map-host-loopback; Podman's host.containers.internal reaches only the host's outside address).
HOST_LOOPBACK = "169.254.1.3"
GENERATED = "generated"
HEADER = "# Generated by `dk host {dir} render` from host.yaml. Don't edit: change host.yaml.\n"

_NAME = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
_HOSTNAME = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")
_DOMAIN = re.compile(r"^[a-z0-9*]([a-z0-9.-]*[a-z0-9])?$")
#: A public key, optionally trusted as an SSH certificate authority for the login.
_KEY = re.compile(
    r'^(cert-authority(,principals="[^"]*")? )?'
    r"(ssh-(ed25519|rsa)|ecdsa-sha2-nistp\d+|sk-\S+) [A-Za-z0-9+/=]+( .*)?$"
)
_DAYS = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")
#: Values written into Butane and unit files: one line, no quoting tricks.
_TIMEZONE = re.compile(r"^[A-Za-z0-9_+-]+(/[A-Za-z0-9_+-]+)*$")
_IMAGE = re.compile(r"^[a-z0-9][A-Za-z0-9._/:@-]*$")
_REGISTRY = re.compile(r"^[a-z0-9][a-z0-9.-]*(:[0-9]+)?$")
_EMAIL = re.compile(r"^[^@\s\"']+@[^@\s\"']+$")


class HostConfigError(ValueError):
    """An invalid or missing host.yaml."""


def uid_of(slot: int) -> int:
    return 1000 + slot


def subuid_of(slot: int) -> int:
    return SUBUID_START + (slot - 1) * SUBUID_COUNT


@dataclass(frozen=True)
class Account:
    name: str
    slot: int
    project: str
    env: str
    role: str = "env"
    #: The names the edge sends here (an env's or a site's account only).
    names: tuple[str, ...] = ()

    @property
    def uid(self) -> int:
        return uid_of(self.slot)

    @property
    def subuid_start(self) -> int:
        return subuid_of(self.slot)

    def port(self, n: int = 0) -> int:
        """The account's n-th loopback port (0: what the edge, or the site's front, sends to)."""
        if not 0 <= n < PORTS_PER_SLOT:
            raise ValueError(f"an account has {PORTS_PER_SLOT} ports (0-{PORTS_PER_SLOT - 1})")
        return PORT_BASE + self.slot * PORTS_PER_SLOT + n

    @property
    def home(self) -> str:
        return f"/var/home/{self.name}"

    @property
    def quadlet_dir(self) -> str:
        return f"/etc/containers/systemd/users/{self.uid}"


@dataclass(frozen=True)
class HostConfig:
    dir: Path
    hostname: str
    timezone: str
    admin_keys: tuple[str, ...]
    ssh_authorized_keys: tuple[str, ...]
    accounts: tuple[Account, ...]
    update_window: UpdateWindow = field(default_factory=UpdateWindow)
    data_mount: str = "/var/mnt/data"
    edge_image: str = DEFAULT_EDGE_IMAGE
    edge_tls: str = "acme"
    acme_email: str | None = None
    retired_slots: tuple[int, ...] = ()
    #: Plain-HTTP registries (a test registry on a VM's host); never for a real server.
    insecure_registries: tuple[str, ...] = ()
    raw_text: str = field(default="", compare=False)

    @property
    def name(self) -> str:
        return self.dir.name

    @property
    def edge(self) -> Account:
        return Account(name=EDGE_USER, slot=EDGE_SLOT, project="", env="", role="edge")

    def account(self, name: str) -> Account:
        for a in self.accounts:
            if a.name == name:
                return a
        raise KeyError(name)

    def accounts_of(self, project: str, env: str) -> dict[str, Account]:
        """{role: account} for one env: ``{"env": …}`` or ``{"site", "blue", "green"}``."""
        return {a.role: a for a in self.accounts if a.project == project and a.env == env}

    def data_dir(self, account: Account) -> str:
        return f"{self.data_mount}/{account.name}"

    @property
    def generated_dir(self) -> Path:
        return self.dir / GENERATED


# --- host.yaml ------------------------------------------------------------------------------


def host_yaml(host_dir: Path) -> Path:
    return host_dir / "host.yaml"


def load_host(host_dir: Path) -> HostConfig:
    path = host_yaml(host_dir)
    if not path.is_file():
        raise HostConfigError(f"{path} is missing (an env's `host:` names a folder with a host.yaml)")
    text = path.read_text(encoding="utf-8")
    try:
        raw = yaml.safe_load(text) or {}
    except yaml.YAMLError as exc:
        raise HostConfigError(f"{path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise HostConfigError(f"{path}: expected a mapping")
    known = {
        "hostname", "timezone", "admin_keys", "ssh_authorized_keys", "update_window",
        "data_mount", "edge", "retired_slots", "accounts", "insecure_registries",
    }  # fmt: skip
    unknown = sorted(set(raw) - known)
    if unknown:
        raise HostConfigError(f"{path}: unknown keys {', '.join(unknown)}")
    where = f"{path}"

    hostname = str(raw.get("hostname") or host_dir.name)
    if not _HOSTNAME.fullmatch(hostname):
        raise HostConfigError(f"{where}: hostname must be a host name label (got {hostname!r})")
    admin_keys = _keys(raw.get("admin_keys"), "admin_keys", where)
    if not admin_keys:
        raise HostConfigError(f"{where}: admin_keys is empty (core's keys: admins, root through sudo)")
    ssh_keys = _keys(raw.get("ssh_authorized_keys"), "ssh_authorized_keys", where)
    if not ssh_keys:
        raise HostConfigError(f"{where}: ssh_authorized_keys is empty (the keys dk logs in to each account with)")
    retired = raw.get("retired_slots") or []
    if not isinstance(retired, list) or not all(isinstance(s, int) and not isinstance(s, bool) for s in retired):
        raise HostConfigError(f"{where}: retired_slots must be a list of slot numbers")
    data_mount = str(raw.get("data_mount") or "/var/mnt/data").rstrip("/")
    if not data_mount.startswith("/var/"):
        raise HostConfigError(f"{where}: data_mount must be under /var (FCOS keeps data there)")
    edge = raw.get("edge") or {}
    if not isinstance(edge, dict) or set(edge) - {"image", "tls", "email"}:
        raise HostConfigError(f"{where}: edge takes image, tls (acme or internal) and email")
    tls = str(edge.get("tls") or "acme")
    if tls not in ("acme", "internal"):
        raise HostConfigError(f"{where}: edge.tls must be acme or internal (got {tls!r})")

    timezone = str(raw.get("timezone") or "UTC")
    if not _TIMEZONE.fullmatch(timezone):
        raise HostConfigError(f"{where}: timezone must be a zone name such as Asia/Dili (got {timezone!r})")
    if not _IMAGE.fullmatch(str(edge.get("image") or DEFAULT_EDGE_IMAGE)):
        raise HostConfigError(f"{where}: edge.image must be an image reference")
    if edge.get("email") and not _EMAIL.fullmatch(str(edge["email"])):
        raise HostConfigError(f"{where}: edge.email must be an email address")
    insecure = raw.get("insecure_registries") or []
    if not isinstance(insecure, list) or not all(isinstance(r, str) and _REGISTRY.fullmatch(r) for r in insecure):
        raise HostConfigError(f"{where}: insecure_registries must be a list of host:port (a test registry)")
    accounts = _accounts(raw.get("accounts"), where, set(retired))
    return HostConfig(
        dir=host_dir,
        hostname=hostname,
        timezone=timezone,
        admin_keys=admin_keys,
        ssh_authorized_keys=ssh_keys,
        accounts=accounts,
        update_window=_update_window(raw.get("update_window"), where),
        data_mount=data_mount,
        edge_image=str(edge.get("image") or DEFAULT_EDGE_IMAGE),
        edge_tls=tls,
        acme_email=str(edge["email"]) if edge.get("email") else None,
        retired_slots=tuple(sorted(retired)),
        insecure_registries=tuple(insecure),
        raw_text=text,
    )


def _keys(raw: Any, key: str, where: str) -> tuple[str, ...]:
    if raw is None:
        return ()
    if not isinstance(raw, list) or not all(isinstance(k, str) and _KEY.match(k.strip()) for k in raw):
        raise HostConfigError(f"{where}: {key} must be a list of public keys")
    return tuple(k.strip() for k in raw)


def _update_window(raw: Any, where: str) -> UpdateWindow:
    if raw is None:
        return UpdateWindow()
    if not isinstance(raw, dict) or set(raw) - {"days", "start", "minutes"}:
        raise HostConfigError(f"{where}: update_window takes days, start and minutes")
    days = tuple(raw.get("days") or ("Sun",))
    if set(days) - set(_DAYS):
        raise HostConfigError(f"{where}: update_window.days: use {', '.join(_DAYS)}")
    start = str(raw.get("start", "02:00"))
    if not re.fullmatch(r"([01][0-9]|2[0-3]):[0-5][0-9]", start):
        raise HostConfigError(f"{where}: update_window.start must be HH:MM")
    minutes = raw.get("minutes", 60)
    if not isinstance(minutes, int) or isinstance(minutes, bool) or not 30 <= minutes <= 1440:
        raise HostConfigError(f"{where}: update_window.minutes must be 30-1440")
    return UpdateWindow(days=days, start=start, minutes=minutes)


def _accounts(raw: Any, where: str, retired: set[int]) -> tuple[Account, ...]:
    if not isinstance(raw, list) or not raw:
        raise HostConfigError(f"{where}: accounts must list at least one account")
    out: list[Account] = []
    seen_names: set[str] = set()
    seen_slots: set[int] = set()
    seen_domains: dict[str, str] = {}
    for i, entry in enumerate(raw):
        at = f"{where}: accounts[{i}]"
        if not isinstance(entry, dict) or set(entry) - {"name", "slot", "project", "env", "role", "names"}:
            raise HostConfigError(f"{at} takes name, slot, project, env, role and names")
        name = str(entry.get("name") or "")
        if not _NAME.fullmatch(name):
            raise HostConfigError(f"{at}: name must be an account name (got {name!r})")
        if name in ("root", "core", EDGE_USER):
            raise HostConfigError(
                f"{at}: {name} is reserved (core: admins; edge: the shared edge's account)"
            )
        if name in seen_names:
            raise HostConfigError(f"{at}: account {name} is listed twice")
        slot = entry.get("slot")
        if not isinstance(slot, int) or isinstance(slot, bool) or not 1 <= slot <= MAX_SLOT:
            raise HostConfigError(f"{at}: slot must be 1-{MAX_SLOT} (got {slot!r})")
        if slot in retired:
            raise HostConfigError(f"{at}: slot {slot} is retired; a slot is never handed out again")
        if slot in seen_slots:
            raise HostConfigError(f"{at}: slot {slot} is already taken: each account has its own")
        project, env = str(entry.get("project") or ""), str(entry.get("env") or "")
        if not project or not env:
            raise HostConfigError(f"{at}: project and env name the env this account runs")
        role = str(entry.get("role") or "env")
        if role not in ROLES:
            raise HostConfigError(f"{at}: role must be one of {', '.join(ROLES)} (got {role!r})")
        names = entry.get("names") or []
        if not isinstance(names, list) or not all(isinstance(n, str) and _DOMAIN.fullmatch(n) for n in names):
            raise HostConfigError(f"{at}: names must be a list of domain names")
        if names and role in COLOURS:
            raise HostConfigError(
                f"{at}: the edge sends a blue/green env's names to its site account, not to a colour"
            )
        for n in names:
            if n in seen_domains:
                raise HostConfigError(f"{at}: {n} is already {seen_domains[n]}'s")
            seen_domains[n] = name
        seen_names.add(name)
        seen_slots.add(slot)
        out.append(Account(name, slot, project, env, role, tuple(names)))

    groups: dict[tuple[str, str], list[str]] = {}
    for a in out:
        groups.setdefault((a.project, a.env), []).append(a.role)
    for (project, env), roles in groups.items():
        if roles == ["env"]:
            continue
        if sorted(roles) != ["blue", "green", "site"]:
            raise HostConfigError(
                f"{where}: {project} {env} has roles {sorted(roles)}: one account (role env) for a "
                "plain env, or exactly site, blue and green for a blue/green one"
            )
    return tuple(out)


# --- render ---------------------------------------------------------------------------------


def ports_range(a: Account) -> tuple[int, int]:
    return a.port(0), a.port(PORTS_PER_SLOT - 1)


def manifest(host: HostConfig) -> dict:
    return {
        "hostname": host.hostname,
        "edge": {"user": EDGE_USER, "uid": host.edge.uid, "image": host.edge_image},
        "accounts": {
            a.name: {
                "slot": a.slot,
                "uid": a.uid,
                "subuid_start": a.subuid_start,
                "ports": list(ports_range(a)),
                "project": a.project,
                "env": a.env,
                "role": a.role,
            }
            for a in host.accounts
        },
        "routes": {n: a.port() for a in host.accounts for n in a.names},
        "retired_slots": list(host.retired_slots),
    }


def edge_caddy_json(host: HostConfig) -> str:
    """Each account's names to its first loopback port, TLS here (fd 3/4/5 from edge.socket)."""
    routes = [
        {
            "match": [{"host": list(a.names)}],
            "handle": [{"handler": "reverse_proxy", "upstreams": [{"dial": f"127.0.0.1:{a.port()}"}]}],
            "terminal": True,
        }
        for a in host.accounts
        if a.names
    ]
    config: dict = {"apps": {"http": {"servers": {"edge": {"listen": [":443"], "routes": routes}}}}}
    if host.edge_tls == "internal":
        issuer: dict = {"module": "internal"}
    else:
        issuer = {"module": "acme", **({"email": host.acme_email} if host.acme_email else {})}
    config["apps"]["tls"] = {"automation": {"policies": [{"issuers": [issuer]}]}}
    # The edge is on the host's network: its admin API on 127.0.0.1:2019 would let any account
    # that reaches the host's loopback change its routes. Its routes change only with a new
    # server, so it has none (measured on the VM: `ss` listed 127.0.0.1:2019 before this).
    config["admin"] = {"disabled": True}
    return json.dumps(rewrite_listeners(config), indent=2, sort_keys=True) + "\n"


def edge_container(host: HostConfig) -> str:
    home = host.edge.home
    return (
        "[Unit]\n"
        "Description=the shared edge: TLS for every name on the host, each to its account\n"
        "Requires=edge.socket\n"
        "After=edge.socket\n"
        "\n"
        "[Container]\n"
        "ContainerName=edge\n"
        f"Image={host.edge_image}\n"
        "# The host's network: each account listens on 127.0.0.1:<its port>.\n"
        "Network=host\n"
        f"Volume={home}/.config/edge/caddy.json:/etc/caddy/caddy.json:ro,Z\n"
        "Volume=edge-data:/data:Z\n"
        "Exec=caddy run --config /etc/caddy/caddy.json\n"
        "\n"
        "[Service]\n"
        "Restart=always\n"
        "\n"
        "[Install]\n"
        "WantedBy=default.target\n"
    )


def firewall_nft(host: HostConfig) -> str:
    """Each account's loopback ports accept only its own env's accounts and the edge.

    Containers that reach the host's loopback (pasta --map-host-loopback) could otherwise reach
    every account's ports; pasta connects as its account, so ``meta skuid`` tells them apart."""
    lines = [
        "# Loopback ports per account: only the account's own env and the edge may connect.",
        "table inet dk_loopback",
        "delete table inet dk_loopback",
        "table inet dk_loopback {",
        "\tchain output {",
        "\t\ttype filter hook output priority 0; policy accept;",
    ]
    for a in host.accounts:
        group = sorted(b.uid for b in host.accounts if (b.project, b.env) == (a.project, a.env))
        uids = ", ".join(str(u) for u in [*group, host.edge.uid])
        low, high = ports_range(a)
        lines.append(
            f'\t\toif "lo" ip daddr 127.0.0.1 tcp dport {low}-{high} meta skuid != {{ {uids} }} '
            f"counter reject with tcp reset  # {a.name}"
        )
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"


